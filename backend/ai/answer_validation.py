def for_preset(preset):
    """A matching catalogue name points to reference evidence, not local proof.

    Hashing installed gigabyte weights during every model-list request would
    create an unbounded UI probe. Only the separate evaluation harness hashes
    its exact artifacts; this record explicitly does not certify a local copy.
    """
    comparison = ANNIVERSARY_REFERENCES.get(preset.get('filename')) or COMPARISON_REFERENCES.get(preset.get('filename'))
    if comparison is not None:
        return deepcopy(comparison)
    if preset.get('filename') != REFERENCE['model_filename']:
        return {'status': 'not_evaluated', 'installed_artifact_verified': False,
                'summary': 'No real-answer evaluation is recorded for this preset. Startup checks only show that inference responds.'}
    return deepcopy(REFERENCE)
