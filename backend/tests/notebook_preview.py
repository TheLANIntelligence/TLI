"""Household Notebook browser QA with temporary notes and inert providers.

Run this script, then open http://127.0.0.1:8772/?desktop=1. The phrase
"simulate failure" fails only the fake model response. No live data is opened.
"""
import conftest as isolation  # temporary persistence and no network BEFORE app imports
import json
from types import SimpleNamespace

import pytest
import uvicorn
import tli_state as S
from ai import ai_manager, ai_routes
from intelligence import devices, memory
from routers import dashboard_presence as dp, home_power, system_routes


def reply(messages):
    question = next((m['content'] for m in reversed(messages) if m.get('role') == 'user'), '')
    if 'simulate failure' in str(question).lower():
        raise RuntimeError('The sample model is unavailable. No request was retried.')
    return ('In this sample notebook, the spare SSD is in the top drawer of the studio cabinet. '
            'This is user-saved information, not a current observation. Check that location before '
            'assuming it is still there.\n\nNo device command, diagnostic or repair was run. '
            'This answer is generated by the test fixture, not a real model.')


if __name__ == '__main__':
    patches = pytest.MonkeyPatch()
    isolation.isolated_background_services.__wrapped__(patches)
    system_routes._ONBOARDING_COMPLETE_FILE.write_text('{}')
    cfg = S.NodeConfig(node_id='notebook-preview-host', node_name='Sample Studio',
                       created_at=S.now_iso(), updated_at=S.now_iso())
    patches.setattr(S, 'load_node_config', lambda: cfg)
    patches.setattr(S, 'load_pin_config', lambda: {'enabled': False})
    patches.setattr(S, 'load_shelly_registry', lambda: [])
    patches.setattr(S, 'load_mesh_directory', lambda: {})
    patches.setattr(home_power, 'get_runtime', lambda: SimpleNamespace(load_devices=lambda: [],
        load_scenes=lambda: [], load_automations=lambda: [], read_receipts=lambda **kw: []))
    S.save_json_file(devices.root() / 'printer_cache.json', {'checked_at': S.now_iso(), 'printers': [
        {'name': 'Sample Office Printer', 'system_name': 'sample-printer', 'location': 'Office'}]})

    import psutil
    patches.setattr(psutil, 'cpu_percent', lambda **kw: 12)
    patches.setattr(psutil, 'virtual_memory', lambda: SimpleNamespace(total=16*1024**3, used=5*1024**3, available=11*1024**3, percent=31))
    patches.setattr(psutil, 'disk_partitions', lambda **kw: [])
    patches.setattr(dp, '_probe_metrics', lambda: {'cpu_pct': 12, 'ram_pct': 31, 'disk_pct_by_drive': {}})
    patches.setattr(dp, '_score_disk_actions', lambda _: None)

    mgr = ai_manager.BundledAIManager.get()
    mgr._active_preset = 'standard'
    patches.setattr(mgr, 'ensure_running', lambda: True)
    patches.setattr(mgr, 'is_healthy', lambda: True)
    patches.setattr(mgr, 'status', lambda: {'healthy': True, 'running': True, 'model_exists': True,
        'active_preset': 'standard', 'base_url': 'http://127.0.0.1:19998', 'model_name': 'Sample notebook model'})
    patches.setattr(ai_routes, '_should_prefer_mesh', lambda: False)
    patches.setattr(ai_routes, '_find_mesh_ai_peer', lambda: None)
    def fake_post(base_url, payload, timeout_s=60, **kwargs):
        return {'model': 'Sample notebook model', 'choices': [{'message': {'content': reply(payload['messages'])}}]}
    def fake_stream(url, payload, **kwargs):
        try:
            answer = reply(payload['messages'])
        except RuntimeError as error:
            yield json.dumps({'type': 'error', 'detail': str(error)})
            return
        for line in answer.splitlines(keepends=True):
            yield json.dumps({'choices': [{'delta': {'content': line}}]})
    patches.setattr(ai_routes, '_llama_post', fake_post)
    patches.setattr(ai_routes, '_llama_stream_raw', fake_stream)
    patches.setattr(S, 'lm_provider', SimpleNamespace(health_check=lambda: True,
        health_report=lambda: {'reachable': True, 'base_url': 'http://127.0.0.1:19998', 'model': 'Sample notebook model'},
        list_models=lambda: {'models': [{'id': 'sample-notebook-model'}]},
        complete=lambda **kw: {'text': reply(kw['messages']), 'model': 'Sample notebook model'}))

    # Seed only the temporary, PIN-disabled owner used by this isolated browser.
    S.save_memory('local', {'facts': [
        {'id': 'sample-spare-drive', 'title': 'Spare SSD location', 'text': 'The spare SSD is in the top drawer of the studio cabinet.',
         'category': 'general', 'source': 'user', 'device_id': None, 'created_at': '2026-09-01T12:00:00Z', 'updated_at': '2026-09-01T12:00:00Z'},
        {'id': 'sample-printer-paper', 'title': 'Printer paper', 'text': 'The office printer uses A4 plain paper. Spare packs are on the lower office shelf.',
         'category': 'device', 'source': 'user', 'device_id': devices.stable_id('printer', 'sample-printer'), 'created_at': '2026-09-02T12:00:00Z', 'updated_at': '2026-09-02T12:00:00Z'},
        {'id': 'sample-old-preference', 'text': 'I prefer short answers with the observation time included.', 'category': 'preference'},
    ]})
    print(f'Disposable notebook preview: {isolation.TEST_ROOT}', flush=True)
    uvicorn.run(isolation._main.app, host='127.0.0.1', port=8772, log_level='warning')
