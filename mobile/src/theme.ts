export type PaletteId = typeof PALETTES[number]['id'];
export type Theme = { readonly [K in keyof typeof PALETTES[number]]: K extends 'dark' ? boolean : string } & { readonly id: PaletteId; readonly emerald: string };
export const DEFAULT_PALETTE: PaletteId = 'emeraldLight';
const aliases: Readonly<Record<string, PaletteId>> = { cloud: 'cloudLight', emeraldDark: 'midnight' };
export function paletteById(id: unknown): Theme {
  const key = typeof id === 'string' ? aliases[id] || id : DEFAULT_PALETTE;
  const palette = PALETTES.find(item => item.id === key) || PALETTES[0];
  return { ...palette, emerald: palette.accent };
}
export function isPaletteId(id: unknown): id is PaletteId { return PALETTES.some(item => item.id === id); }
export function mixColors(first: string, second: string, firstWeight: number): string {
  const weight = Math.max(0, Math.min(1, firstWeight));
  const channel = (value: string, at: number) => parseInt(value.slice(at, at + 2), 16);
  return '#' + [1, 3, 5].map(at => Math.round(channel(first, at) * weight + channel(second, at) * (1 - weight)).toString(16).padStart(2, '0')).join('');
}
