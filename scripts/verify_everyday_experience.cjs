/* Real application UI and routes, disposable experience_preview.py backend only. */
const {chromium} = require('playwright');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const output = path.resolve(__dirname, '../build_work/everyday-experience');
fs.mkdirSync(output, {recursive:true});
(async () => {
  const browser = await chromium.launch({headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1280,height:900}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
    await page.goto('http://127.0.0.1:8791/?desktop=1');
    await page.waitForFunction(() => window.TLIExperience && window.TLITroubleshooting && window.TLIWebApps);
    await page.evaluate(() => switchPanel('panel-main'));
    assert.equal(await page.locator('#tli-connected-tools').getAttribute('open'), null);
    await page.locator('#quickstart-chips').getByRole('button', {name:'Help me write',exact:true}).click();
    assert.match(await page.locator('#chat-input').inputValue(), /Help me write something/);
    assert.equal(await page.locator('#panel-main').evaluate(el => el.classList.contains('active')), true);
    assert.equal(await page.locator('#chat-output .chat-msg--user').count(), 0);
    await page.locator('#chat-input').fill('');
    await page.screenshot({path:path.join(output,'general-ai-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1));
    await page.screenshot({path:path.join(output,'general-ai-phone.png'),fullPage:true});
    await page.setViewportSize({width:1280,height:900});
    console.log(JSON.stringify({check:'General conversation is the default; writing starter stays in chat without sending or opening tools',passed:true}));
    await page.locator('#tli-connected-tools > summary').click();
    await page.locator('#chat-input').fill('My sample computer slows down during a call.');
    await page.locator('#tli-start-computer').click();
    await page.waitForFunction(() => document.getElementById('troubleshooting-symptom')?.value === 'My sample computer slows down during a call.');
    assert.equal(await page.locator('#chat-input').inputValue(), 'My sample computer slows down during a call.');
    await page.screenshot({path:path.join(output,'computer-help.png'),fullPage:true});
    console.log(JSON.stringify({check:'Ask TLI hands off a problem and preserves chat draft',passed:true}));
    await page.locator('#troubleshooting-computer').selectOption('node-sample-host');
    await page.getByRole('button',{name:'Save problem',exact:true}).click();
    await page.waitForFunction(() => document.getElementById('troubleshooting-save-state')?.textContent.startsWith('Saved'));
    await page.getByRole('button',{name:'Review available checks',exact:true}).click();
    await page.locator('.troubleshooting-check-option').filter({hasText:'Check host resources'}).getByRole('button',{name:'Review this check',exact:true}).click();
    await page.getByRole('button',{name:'Run this check',exact:true}).click();
    await page.getByRole('button',{name:'Save report with this problem',exact:true}).click();
    await page.waitForFunction(() => document.getElementById('troubleshooting-status')?.textContent.includes('Report and problem saved together'));
    await page.getByRole('button',{name:'Record what happened',exact:true}).click();
    await page.locator('#troubleshooting-resolution').fill('The sample improved after closing an extra application. User observation, not a measured repair.');
    await page.locator('#troubleshooting-state').selectOption('resolved');
    await page.getByRole('button',{name:'Save outcome',exact:true}).click();
    await page.getByRole('button',{name:'Reopen and save',exact:true}).click();
    await page.waitForFunction(() => document.getElementById('troubleshooting-status')?.textContent.includes('Investigation reopened'));
    const cases = await page.request.get('http://127.0.0.1:8791/api/intelligence/cases');
    const row = (await cases.json()).items.find(row => row.symptom === 'My sample computer slows down during a call.');
    const saved = (await (await page.request.get('http://127.0.0.1:8791/api/intelligence/cases/' + row.id)).json()).case;
    assert.ok(saved && saved.status === 'open' && saved.evidence.length === 1);
    assert.match(saved.resolution, /sample improved/);
    console.log(JSON.stringify({check:'Observed report saved with problem; outcome and history survive reopening',passed:true}));
    await page.evaluate(() => switchPanel('panel-main'));
    await page.locator('#chat-input').fill('Turn on Sample Lamp');
    await page.locator('#chat-send-btn').click();
    await page.waitForFunction(() => document.getElementById('chat-output').textContent.includes('acknowledged the on command'));
    assert.match(await page.locator('#chat-output').innerText(), /ON/);
    console.log(JSON.stringify({check:'Chat commands synthetic lamp once and renders its verified state',passed:true}));
    await page.screenshot({path:path.join(output,'smart-home-chat.png'),fullPage:true});
    await page.locator('#chat-input').fill('Build a simple counter with an Add button.');
    await page.locator('#tli-start-build').click();
    await page.locator('#builder-app-brief').waitFor({timeout:5000});
    await page.waitForFunction(() => document.getElementById('builder-app-brief')?.value === 'Build a simple counter with an Add button.');
    assert.equal(await page.locator('#builder-app-brief').inputValue(), 'Build a simple counter with an Add button.');
    await page.getByRole('button',{name:'Build with local AI',exact:true}).click();
    await page.getByRole('button',{name:'Open isolated preview',exact:true}).click();
    const preview = page.frameLocator('#builder-web-apps .builder-app-preview iframe');
    await preview.locator('#add').click(); await preview.locator('#add').click();
    assert.equal(await preview.locator('#count').innerText(),'2');
    await page.getByRole('button',{name:'Run browser checks',exact:true}).click();
    await page.waitForFunction(() => document.querySelector('.builder-app-status')?.textContent.startsWith('Browser checks passed'));
    await page.locator('#builder-app-feedback').fill('Make each Add increase the counter by 2.');
    await page.getByRole('button',{name:'Repair / improve with local AI',exact:true}).click();
    await page.getByLabel('Saved app version').selectOption('2');
    await page.getByRole('button',{name:'Open isolated preview',exact:true}).click();
    await preview.locator('#add').click();
    assert.equal(await preview.locator('#count').innerText(),'2');
    await page.getByLabel('Saved app version').selectOption('1');
    await page.getByRole('button',{name:'Open isolated preview',exact:true}).click();
    await preview.locator('#add').click();
    assert.equal(await preview.locator('#count').innerText(),'1');
    const download = await page.request.get(new URL(await page.getByRole('link',{name:'Download this version'}).getAttribute('href'),page.url()).href);
    assert.equal(download.status(),200); assert.equal(download.headers()['content-type'],'application/zip');
    console.log(JSON.stringify({check:'App builds, executes independently checked behavior, revises, preserves old version and downloads',passed:true}));
    await page.screenshot({path:path.join(output,'builder.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.locator('#builder-web-apps').scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1));
    await page.screenshot({path:path.join(output,'phone-builder.png'),fullPage:true});
    await page.evaluate(() => switchPanel('panel-main'));
    await page.locator('#chat-input').scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1));
    await page.screenshot({path:path.join(output,'phone-chat.png'),fullPage:true});
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output,'browser-results.json'),JSON.stringify({passed:true,synthetic:true,errors,viewports:[1280,390]},null,2));
    console.log(JSON.stringify({errors}));
  } finally { await browser.close(); }
})().catch(error => {console.error(error);process.exitCode=1;});
